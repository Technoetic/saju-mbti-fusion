"""조상 메시지 정서 어휘 풀 + 흐름 톤.

학술 근거 (ADR-123):
  - 이능화 (1927) 조선무속고 — 가정신앙 삼신 추상 형이상학 (개별 망자 X)
  - 한국학중앙연구원 한국민족문화대백과사전 — 조상숭배·조상굿 표제
  - 국립민속박물관 한국민속대백과사전 — 사령숭배 정의
  - 임석재·김태곤·황루시 정통 민속학 연구

본 어휘 풀은 망자 1인칭 빙의 화법·접신 어휘를 영구 차단하고,
한국 전통 추모 정서 (효·근원·인연·뿌리)와 무속 형이상학적 보호막 (음덕·수호)
어휘만 LLM 시스템 프롬프트에 주입한다.
"""
from __future__ import annotations

from typing import List


# 정통 학파 어휘 10건 (이능화·한국학중앙연구원·국립민속박물관)
ANCESTOR_FLOW_TONE_VOCAB: frozenset = frozenset({
    "효(孝)",
    "근원의 결",
    "인연의 흐름",
    "내리사랑",
    "뿌리",
    "수호",
    "보살핌",
    "음덕(陰德)",
    "선대의 자취",
    "보이지 않는 이끌림",
})

# 보고서 §3.2 명시 3 표준 흐름 톤 예문
RECOMMENDED_FLOW_TONES: List[str] = [
    "선대로부터 길게 이어져 온 인연의 결이 당신의 앞길에 조용한 평안을 기원하고 있습니다.",
    "생명의 근원으로 돌아가는 고마움의 정서가 당신의 현재 운기에 긍정적이고 따뜻한 파동을 만들어냅니다.",
    "이름 모를 조상의 결이 비치는 흐름 속에서, 흔들리지 않는 뿌리를 잊지 않는 마음 씀씀이가 곧 재수와 발복으로 이어질 결입니다.",
]


def build_ancestor_prompt_injection() -> str:
    """LLM 시스템 프롬프트 주입용 조상 카드 가이드 문자열.

    palm '조상님의 메시지' 카드 분기에서 web/server.py가 본 함수 결과를
    LLM 시스템 프롬프트에 주입하여 단정·1인칭 빙의 화법을 차단한다.

    Returns:
        str: LLM 시스템 프롬프트 주입 텍스트.
    """
    vocab_list = "·".join(sorted(ANCESTOR_FLOW_TONE_VOCAB))
    tones = "\n".join(f"  - {tone}" for tone in RECOMMENDED_FLOW_TONES)
    return (
        "[조상님의 메시지 카드 — 작문 가이드]\n"
        "본 카드는 한국 무속 정통 학파 (이능화 1927·한국학중앙연구원·"
        "국립민속박물관) 정합 추모 문화 콘텐츠다.\n"
        "\n"
        "정통 학파 어휘 풀 (반드시 활용):\n"
        f"  {vocab_list}\n"
        "\n"
        "권장 흐름 톤 (3인칭 추상·보살핌·축원):\n"
        f"{tones}\n"
        "\n"
        "절대 금지 (자문 거절 정신 의무):\n"
        "  - 망자 1인칭 빙의 화법 (예: '내가 너를 늘 지켜보고 있다')\n"
        "  - 접신·빙의·신내림·영안·채널링 어휘\n"
        "  - 망자의 음성·영혼의 대화 단정\n"
        "  - 사망 원인 단정 (예: '위장병으로 돌아가신 조상')\n"
        "  - 전생·윤회·업보 단정\n"
        "  - 저승사자·환생·지옥 묘사\n"
        "\n"
        "3인칭 추상 보살핌 톤으로 한국 전통 추모 정서를 서정적으로 축원하라."
    )
