// 카드 키 → 카드 객체 룩업
export function getPsychoCard(key) {
  return PSYCHOTEST.cards.find(c => c.key === key) || null;
}

// 모든 카드 키 리스트
export function listPsychoCardKeys() {
  return PSYCHOTEST.cards.map(c => c.key);
}
